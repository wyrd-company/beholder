#!/usr/bin/env python3
"""Re-render docs/gate5-evaluation.toml from the reports it records.

The evaluation is evidence, so every mechanical figure in it has to come from
beholder rather than from a person retyping numbers: the corpus, the surfaced
counts and the top entries are regenerated by running the reports again.

Judgement does not regenerate. Which pull request a revision stands for, whether
a report landed on its subject, and whether an entry was promoted by fan-in
nobody stated are read from the existing file and carried over, keyed by
revision and symbol. An entry that is new to a report gets its judgement fields
left at their default and is listed at the end for a human to rule on.

Which changes surface is never decided here. The surfaced set is read out of the
SARIF beholder emits, so this script cannot drift from the ranking it documents.

    python3 scripts/gate5-evaluation.py [--check]
"""

from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RECORD = ROOT / "docs" / "gate5-evaluation.toml"
WORKSPACE = ROOT.parent.parent.parent / "tools"
BASES = ("raw", "damped")
TOP = 5


def run_report(beholder: pathlib.Path, repository: str, revision: str, basis: str):
    root = WORKSPACE / repository
    report = subprocess.run(
        [beholder, "report", f"{revision}~1", revision, "--root", str(root),
         "--basis", basis, "--format", "json"],
        check=True, capture_output=True, text=True,
    ).stdout
    sarif = subprocess.run(
        [beholder, "render", "--format", "sarif"],
        check=True, capture_output=True, text=True, input=report,
    ).stdout
    return json.loads(report), json.loads(sarif)


def surfaced_entries(report, sarif):
    """The surfaced changes, in beholder's own order, with their metadata.

    The order and the membership come from the SARIF results; the metadata comes
    from the report. Nothing here re-decides what surfaces.
    """
    by_id = {change["id"]: change for change in report["changes"]}
    ids = [
        result["partialFingerprints"]["beholderSymbol/v1"]
        for result in sarif["runs"][0]["results"]
    ]
    return [by_id[symbol_id] for symbol_id in ids]


def classify(change) -> str:
    if " as " in change["qualified_path"]:
        return "trait_impl_method"
    if "::" in change["qualified_path"]:
        return "associated_item"
    return "free_item"


def is_test_file(path: str) -> bool:
    parts = pathlib.PurePosixPath(path).parts
    name = parts[-1]
    return "tests" in parts[:-1] or name.startswith("test_") or "_test." in name


def entry(rank: int, change, judged: dict) -> dict:
    key = (change["qualified_path"], change["path"])
    return {
        "rank": rank,
        "symbol": change["qualified_path"],
        "path": change["path"],
        "classification": classify(change),
        "complexity_delta": change["complexity_delta"],
        "fan_in": change["fan_in"],
        "fan_in_stated": change["fan_in_high_confidence"],
        "is_test_file": is_test_file(change["path"]),
        "is_trait_method": change["caveat"] == "trait_method_fan_in_unreliable",
        "trivial_promoted_by_unstated_fan_in": judged.get(key, False),
    }


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        if "\n" in value:
            return '"""\n' + value + '"""'
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    return str(value)


def emit(previous, changes) -> str:
    out = [HEADER.lstrip("\n")]

    out.append("[corpus]")
    for key, value in previous["corpus"].items():
        out.append(f"{key} = {toml_value(value)}")

    summary = dict(previous["summary"])
    summary["reports"] = len(changes)
    summary["on_subject"] = sum(1 for c in changes if c["verdict"].startswith("on subject"))
    summary["thin"] = sum(1 for c in changes if c["verdict"].startswith("thin"))
    for basis in BASES:
        summary[f"trivial_promoted_by_unstated_fan_in_{basis}"] = sum(
            e["trivial_promoted_by_unstated_fan_in"]
            for c in changes for e in c[f"{basis}_top"]
        )
    # Where the two bases surface the same top five, the choice between them
    # does not matter; the claim that damping earns its keep rests on the rest,
    # so the count belongs here rather than in prose no check can protect.
    summary["reports_where_bases_agree_on_top_five"] = sum(
        [e["symbol"] for e in c["raw_top"]] == [e["symbol"] for e in c["damped_top"]]
        for c in changes
    )
    summary["test_file_entries_in_top_five_damped"] = sum(
        e["is_test_file"] for c in changes for e in c["damped_top"]
    )
    summary["damped_top_five_entries"] = sum(len(c["damped_top"]) for c in changes)
    summary["trait_method_entries_in_top_five_damped"] = sum(
        e["is_trait_method"] for c in changes for e in c["damped_top"]
    )

    out.append("\n[summary]")
    out.append(SUMMARY_COMMENT)
    for key, value in summary.items():
        out.append(f"{key} = {toml_value(value)}")

    for change in changes:
        out.append("\n[[change]]")
        # Every scalar before any sub-table. A key written after a
        # [[change.raw_top]] table would belong to that table, not to the
        # change — which is how an earlier hand-written revision of this file
        # came to file damped_surfaced under the last raw entry.
        for key in ("repository", "revision", "pull_request", "changed_symbols", "verdict"):
            out.append(f"{key} = {toml_value(change[key])}")
        for basis in BASES:
            out.append(f"{basis}_surfaced = {change[f'{basis}_surfaced']}")
        for basis in BASES:
            for item in change[f"{basis}_top"]:
                out.append(f"\n[[change.{basis}_top]]")
                for key, value in item.items():
                    out.append(f"{key} = {toml_value(value)}")

    return "\n".join(out) + "\n"


HEADER = """
# Gate 5 - report usefulness. Machine-readable evaluation record.
#
# Regenerate with:
#   python3 scripts/gate5-evaluation.py
#
# Mechanical figures come from re-running the reports; which entries surfaced is
# read out of beholder's own SARIF rather than recomputed here. Judgement fields
# - pull_request, verdict, trivial_promoted_by_unstated_fan_in - are carried
# over by revision and symbol, because no script can form a judgement.
#
# Every figure in [summary] is computable from the [[change]] entries below:
# each records the top five surfaced entries per basis with the metadata the
# summary counts over. Nothing here is asserted without its evidence.
"""

SUMMARY_COMMENT = """# Counted over the top five surfaced entries of all fourteen reports; every
# figure is a count over the [[change.*_top]] entries below. Field names carry
# the basis they describe, because the two bases surface different entries."""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if the record is out of date instead of rewriting it")
    parser.add_argument("--beholder", type=pathlib.Path,
                        default=ROOT / "target" / "release" / "beholder")
    args = parser.parse_args()

    previous = tomllib.loads(RECORD.read_text())
    judged = {
        change["revision"]: {
            (e["symbol"], e["path"]): e["trivial_promoted_by_unstated_fan_in"]
            for basis in BASES for e in change.get(f"{basis}_top", [])
        }
        for change in previous["change"]
    }

    changes = []
    unjudged = []
    for previous_change in previous["change"]:
        revision = previous_change["revision"]
        record = {
            "repository": previous_change["repository"],
            "revision": revision,
            "pull_request": previous_change["pull_request"],
            "verdict": previous_change["verdict"],
        }
        for basis in BASES:
            report, sarif = run_report(
                args.beholder, previous_change["repository"], revision, basis)
            record["changed_symbols"] = len(report["changes"])
            entries = surfaced_entries(report, sarif)
            record[f"{basis}_surfaced"] = len(entries)
            record[f"{basis}_top"] = [
                entry(rank, change, judged[revision])
                for rank, change in enumerate(entries[:TOP], start=1)
            ]
            for item in record[f"{basis}_top"]:
                if (item["symbol"], item["path"]) not in judged[revision]:
                    unjudged.append(f"{revision[:8]} {basis} {item['symbol']}")
        changes.append(record)
        print(f"{revision[:8]} {record['repository']}: "
              f"raw {record['raw_surfaced']}, damped {record['damped_surfaced']}",
              file=sys.stderr)

    rendered = emit(previous, changes)
    if args.check:
        if rendered != RECORD.read_text():
            print("docs/gate5-evaluation.toml is out of date", file=sys.stderr)
            return 1
        print("docs/gate5-evaluation.toml is current", file=sys.stderr)
        return 0

    RECORD.write_text(rendered)
    if unjudged:
        print("\nentries with no carried judgement, rule on these:", file=sys.stderr)
        for line in unjudged:
            print(f"  {line}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
